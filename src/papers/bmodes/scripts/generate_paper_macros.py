# Version number to word mapping for TeX-safe macro names
# (avoids cleveref/siunitx conflict with numeric names)
def _sig3(x):
    """Format a float to 3 significant figures; scientific for |x|<1e-3 or >=1e4, else fixed."""
    if x == "" or x is None:
        return ""
    x = float(x)
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    if e < -3 or e >= 4:
        return f"{x:.2e}"  # mantissa carries 3 sig figs, e.g. 7.37e-10
    return f"{x:.{max(0, 2 - e)}f}"  # 3 sig figs fixed, e.g. 0.938, 0.00461


VERSION_WORDS = {
    "5": "Five",
    "6": "Six",
    "6.3": "SixThree",
    "8": "Eight",
    "11.2": "ElevenTwo",
    "11.3": "ElevenThree",
}


def _parse_version_short(version: str) -> str:
    """Extract short version number from full version string.

    Examples:
        "SP_v1.4.6_leak_corr" → "6"
        "SP_v1.4.11.2" → "11.2"
    """
    return version.split("v1.4.")[1].split("_")[0]


def _format_value(value, bold_threshold=None, italic_threshold=None) -> str:
    """Format a value for LaTeX.

    Parameters
    ----------
    bold_threshold : float, optional
        If set and value is a float below this threshold, wrap in \\textbf{}.
    italic_threshold : float, optional
        If set and value is a float below this threshold, wrap in \\textit{}.
        Checked after bold_threshold, so bold takes precedence.
    """
    if isinstance(value, float):
        if math.isnan(value):
            return "--"
        if abs(value) < 0.001 and value != 0:
            text = rf"\num{{{value:.2e}}}"
        elif abs(value) < 0.1:
            text = rf"\num{{{value:.3f}}}"
        else:
            text = rf"\num{{{value:.2f}}}"
        if bold_threshold is not None and value < bold_threshold:
            return rf"\textbf{{{text}}}"
        if italic_threshold is not None and value < italic_threshold:
            return rf"\textit{{{text}}}"
        return text
    elif isinstance(value, int):
        return rf"\num{{{value}}}"
    elif isinstance(value, str):
        return value.replace("_", r"\_")
    elif isinstance(value, list):
        return ", ".join(_format_value(v) for v in value)
    else:
        return str(value)


def generate_macros(
    claims_dir: Path,
    output_paths: list[Path],
    fiducial_version: str,
    config_pte_path: Path = None,
    harmonic_pte_path: Path = None,
    mock_min_pte_calibration_path: Path = None,
    harmonic_config_fiducial_path: Path = None,
    harmonic_config_full_path: Path = None,
    scale_cut_convention: str = "rounded_arcmin",
    reporting=None,
    pte_threshold: float = None,
    mock_campaign_evidence_path: Path = None,
    mock_scale_cut_scan_path: Path = None,
    survey_properties_path: Path = None,
    cosebis_modes_path: Path = None,
    mock_per_mock_statistics_path: Path = None,
    mock_mean_vector_stats_path: Path = None,
    mock_noise_table_path: Path = None,
    cov_reporting_g_path: Path = None,
    cov_reporting_ng_path: Path = None,
):
    """Generate LaTeX macros from evidence files.

    Macro names are kept simple. The spec (bmodes_paper.md)
    determines which values go into the paper. The fiducial version comes from the catalog decisions.

    ``config_pte_path`` / ``harmonic_pte_path`` override the
    ``claims_dir/<spec_id>/evidence.json`` location for the two PTE-matrix
    evidence files (used by the CLI form, where each lc output lands at its own
    absolute results path rather than under a shared tapestry tree). When
    ``None`` the original ``claims_dir``-relative layout is used.
    """
    macros = []
    macros.append("% Auto-generated by the lightcone output null_tests.pte_summary_macros")
    macros.append(
        "% (src/papers/bmodes/scripts/generate_paper_macros.py --emit macros); do not edit."
    )
    macros.append("")

    # COSEBIS version comparison - extract fiducial version, n=6
    cosebis_path = claims_dir / "cosebis_version_comparison" / "evidence.json"
    if cosebis_path.exists():
        with open(cosebis_path) as f:
            cosebis_ev = json.load(f).get("evidence", {})

        macros.append(f"% cosebis ({fiducial_version}, n=6)")

        # Fiducial scale cut - use pte_6_min (conservative across blinds)
        fiducial = cosebis_ev.get("fiducial", {})
        fid_versions = fiducial.get("versions", {})
        fid_data = fid_versions.get(fiducial_version, {})
        if "pte_6_min" in fid_data:
            macros.append(
                f"\\newcommand{{\\cosebisfiducialPte}}{{{_format_value(fid_data['pte_6_min'])}}}"
            )

        # Full range
        full = cosebis_ev.get("full", {})
        full_versions = full.get("versions", {})
        full_data = full_versions.get(fiducial_version, {})
        if "pte_6_min" in full_data:
            macros.append(
                f"\\newcommand{{\\cosebisfullPte}}{{{_format_value(full_data['pte_6_min'])}}}"
            )

        # Scale cuts from fiducial
        if "scale_cut_arcmin" in fiducial:
            cuts = fiducial["scale_cut_arcmin"]
            macros.append(
                f"\\newcommand{{\\cosebisthetaMin}}{{{_format_value(cuts[0])}}}"
            )
            macros.append(
                f"\\newcommand{{\\cosebisthetaMax}}{{{_format_value(cuts[1])}}}"
            )

        macros.append("")

    # The paper reports rounded arcmin values even when the selected
    # convention resolves to reporting-grid edges. Resolve the decision here,
    # rather than duplicating its values in the macro generator.
    if reporting is not None:
        from scale_cuts import resolve_fiducial_scale_cuts

        theta_min, theta_max = resolve_fiducial_scale_cuts(reporting, scale_cut_convention)
        macros.append("% resolved fiducial pure-mode scale cut")
        macros.append(
            f"\\newcommand{{\\ebthetaXipMin}}{{\\num{{{round(theta_min):.0f}}}}}"
        )
        macros.append(
            f"\\newcommand{{\\ebthetaXipMax}}{{\\num{{{round(theta_max):.0f}}}}}"
        )
        macros.append(
            f"\\newcommand{{\\ebthetaXimMin}}{{\\num{{{round(theta_min):.0f}}}}}"
        )
        macros.append(
            f"\\newcommand{{\\ebthetaXimMax}}{{\\num{{{round(theta_max):.0f}}}}}"
        )
        macros.append("")

    # Pure E/B data vector - use min across blinds (cache for reuse below)
    eb_path = claims_dir / "pure_eb_data_vector" / "evidence.json"
    eb_fid = {}  # cached for PTE variation section
    if eb_path.exists():
        with open(eb_path) as f:
            eb_ev = json.load(f).get("evidence", {})

        macros.append("% pure_eb_data_vector (min across blinds per spec)")

        # Fiducial PTEs - use pte_joint_min (conservative across blinds)
        eb_fid = eb_ev.get("fiducial", {})
        if "pte_joint_min" in eb_fid:
            macros.append(
                f"\\newcommand{{\\ebfiducialPte}}{{{_format_value(eb_fid['pte_joint_min'])}}}"
            )

        # Full range PTEs
        full = eb_ev.get("full", {})
        if "pte_joint_min" in full:
            macros.append(
                f"\\newcommand{{\\ebfullPte}}{{{_format_value(full['pte_joint_min'])}}}"
            )

        macros.append("")

    # Pure E/B covariance structure
    eb_cov_path = claims_dir / "pure_eb_covariance" / "evidence.json"
    if eb_cov_path.exists():
        with open(eb_cov_path) as f:
            data = json.load(f)
        ev = data.get("evidence", {})

        macros.append("% pure_eb_covariance (block condition numbers)")

        # Block condition numbers
        block_analysis = ev.get("block_analysis", {})
        if "xi_E" in block_analysis:
            cond = block_analysis["xi_E"]["condition_number"]
            macros.append(f"\\newcommand{{\\ebcovCondE}}{{\\num{{{cond:.1e}}}}}")
        if "xi_B" in block_analysis:
            cond = block_analysis["xi_B"]["condition_number"]
            macros.append(f"\\newcommand{{\\ebcovCondB}}{{\\num{{{cond:.1e}}}}}")
        if "xi_amb" in block_analysis:
            cond = block_analysis["xi_amb"]["condition_number"]
            macros.append(f"\\newcommand{{\\ebcovCondAmb}}{{\\num{{{cond:.1e}}}}}")

        # Full matrix
        if "condition_number" in ev:
            macros.append(
                f"\\newcommand{{\\ebcovCondFull}}{{\\num{{{ev['condition_number']:.1e}}}}}"
            )
        if "n_bins" in ev:
            macros.append(f"\\newcommand{{\\ebcovNbins}}{{\\num{{{ev['n_bins']}}}}}")

        macros.append("")

    # Covariance blind consistency
    cov_path = claims_dir / "covariance_blind_consistency" / "evidence.json"
    if cov_path.exists():
        with open(cov_path) as f:
            data = json.load(f)
        ev = data.get("evidence", {})

        macros.append("% covariance_blind_consistency")

        # Max deviations across blinds
        xip = ev.get("xip", {})
        xim = ev.get("xim", {})
        xip_max = max(
            xip.get("B_to_A", {}).get("max_dev", 0),
            xip.get("C_to_A", {}).get("max_dev", 0),
        )
        xim_max = max(
            xim.get("B_to_A", {}).get("max_dev", 0),
            xim.get("C_to_A", {}).get("max_dev", 0),
        )
        macros.append(
            f"\\newcommand{{\\covXipMaxDev}}{{{_format_value(xip_max * 100)}\\%}}"
        )
        macros.append(
            f"\\newcommand{{\\covXimMaxDev}}{{{_format_value(xim_max * 100)}\\%}}"
        )

        macros.append("")

    # PTE variation across blinds (reuse eb_fid cached above)
    if eb_fid:
        joint_ptes = [
            eb_fid.get(f"pte_joint_{b}")
            for b in ["A", "B", "C"]
            if f"pte_joint_{b}" in eb_fid
        ]
        if joint_ptes:
            macros.append("% PTE variation across blinds (fiducial scale cuts)")
            joint_delta = max(joint_ptes) - min(joint_ptes)
            macros.append(
                f"\\newcommand{{\\ebJointPteDelta}}{{{_format_value(joint_delta)}}}"
            )
            macros.append("")

    # Config-space PTE matrices - generate table
    if config_pte_path is None:
        config_pte_path = claims_dir / "config_space_pte_matrices" / "evidence.json"
    if config_pte_path.exists():
        with open(config_pte_path) as f:
            data = json.load(f)
        ev = data.get("evidence", {})
        versions = ev.get("versions", {})

        macros.append("% config_space_pte_matrices (all versions)")
        macros.append("")

        # Filter to leak_corr versions only to avoid duplicate macro definitions
        # (both SP_v1.4.6 and SP_v1.4.6_leak_corr map to configPteSix)
        leak_corr_versions = {k: v for k, v in versions.items()
                              if k.endswith("_leak_corr") == fiducial_version.endswith("_leak_corr")}

        # Generate individual macros for each version
        for ver, ver_data in leak_corr_versions.items():
            short_ver = _parse_version_short(ver)
            prefix = f"configPte{VERSION_WORDS.get(short_ver, short_ver)}"

            xip = ver_data.get("xip_stats", {})
            xim = ver_data.get("xim_stats", {})
            combined = ver_data.get("combined_stats", {})
            cosebis = ver_data.get("cosebis_stats", {})
            cosebis_20 = ver_data.get("cosebis_20_stats", {})

            # Fiducial PTEs
            if "pte_at_fiducial" in xip:
                macros.append(
                    f"\\newcommand{{\\{prefix}Xip}}{{{_format_value(xip['pte_at_fiducial'])}}}"
                )
            if "pte_at_fiducial" in xim:
                macros.append(
                    f"\\newcommand{{\\{prefix}Xim}}{{{_format_value(xim['pte_at_fiducial'])}}}"
                )
            if "pte_at_fiducial" in combined:
                macros.append(
                    f"\\newcommand{{\\{prefix}Combined}}{{{_format_value(combined['pte_at_fiducial'])}}}"
                )
            if "pte_at_fiducial" in cosebis:
                macros.append(
                    f"\\newcommand{{\\{prefix}Cosebis}}{{{_format_value(cosebis['pte_at_fiducial'])}}}"
                )
            if "pte_at_fiducial" in cosebis_20:
                macros.append(
                    f"\\newcommand{{\\{prefix}CosebisTwenty}}{{{_format_value(cosebis_20['pte_at_fiducial'])}}}"
                )

            # Full-range PTEs
            if "pte_at_full_range" in xip:
                macros.append(
                    f"\\newcommand{{\\{prefix}XipFull}}{{{_format_value(xip['pte_at_full_range'])}}}"
                )
            if "pte_at_full_range" in xim:
                macros.append(
                    f"\\newcommand{{\\{prefix}XimFull}}{{{_format_value(xim['pte_at_full_range'])}}}"
                )
            if "pte_at_full_range" in combined:
                macros.append(
                    f"\\newcommand{{\\{prefix}CombinedFull}}{{{_format_value(combined['pte_at_full_range'])}}}"
                )
            if "pte_at_full_range" in cosebis:
                macros.append(
                    f"\\newcommand{{\\{prefix}CosebisFull}}{{{_format_value(cosebis['pte_at_full_range'])}}}"
                )
            if "pte_at_full_range" in cosebis_20:
                macros.append(
                    f"\\newcommand{{\\{prefix}CosebisTwentyFull}}{{{_format_value(cosebis_20['pte_at_full_range'])}}}"
                )

        macros.append("")

    # Harmonic-space PTE matrices - generate table
    if harmonic_pte_path is None:
        harmonic_pte_path = claims_dir / "harmonic_space_pte_matrices" / "evidence.json"
    if harmonic_pte_path.exists():
        with open(harmonic_pte_path) as f:
            data = json.load(f)
        ev = data.get("evidence", {})
        versions = ev.get("versions", {})

        macros.append("% harmonic_space_pte_matrices (all versions)")
        macros.append("")

        # Filter to leak_corr versions only (excluding ecut variants) to avoid
        # duplicate macro definitions — both SP_v1.4.6_ecut07_leak_corr and
        # SP_v1.4.6_leak_corr would map to the same clPteSix prefix.
        leak_corr_versions = {
            k: v for k, v in versions.items()
            if k.endswith("_leak_corr") == fiducial_version.endswith("_leak_corr") and "ecut" not in k
        }

        for ver, ver_data in leak_corr_versions.items():
            short_ver = _parse_version_short(ver)
            prefix = f"clPte{VERSION_WORDS.get(short_ver, short_ver)}"

            # Fiducial PTEs
            if "pte_at_fiducial" in ver_data:
                macros.append(
                    f"\\newcommand{{\\{prefix}Fid}}{{{_format_value(ver_data['pte_at_fiducial'])}}}"
                )

            # Full-range PTEs
            if "pte_at_full_range" in ver_data:
                macros.append(
                    f"\\newcommand{{\\{prefix}Full}}{{{_format_value(ver_data['pte_at_full_range'])}}}"
                )

        macros.append("")

    # Mock-calibrated global min-PTE criterion.
    if (
        mock_min_pte_calibration_path is not None
        and mock_min_pte_calibration_path.exists()
    ):
        with open(mock_min_pte_calibration_path) as f:
            calibration = json.load(f)
        observed_ptes = calibration["observed_ptes"]
        min_stat, min_pte = min(observed_ptes.items(), key=lambda item: item[1])
        stat_latex = {
            "xi-^B": r"$\xi_-^{\mathrm{B}}$",
        }
        macros.append("% GLASS mock-calibrated minimum-PTE criterion")
        macros.append(
            f"\\newcommand{{\\mockNRealizations}}{{{calibration['n_mocks']}}}"
        )
        macros.append(
            f"\\newcommand{{\\mockPGlobal}}{{{100 * calibration['p_global_one_sided']:.0f}\\%}}"
        )
        macros.append(
            "\\newcommand{\\mockPGlobalCount}"
            f"{{{calibration['p_global_one_sided_count']}}}"
        )
        macros.append(
            "\\newcommand{\\mockMinPteThreshold}"
            + (
                # The adopted threshold is a round decision value (0.01, 0.05):
                # print it as written, not zero-padded to three decimals.
                f"{{\\num{{{pte_threshold:g}}}}}"
                if pte_threshold is not None
                else f"{{{_format_value(calibration['threshold_one_sided'])}}}"
            )
        )
        macros.append(
            "\\newcommand{\\mockMinPteFloor}"
            f"{{{_format_value(calibration['threshold_one_sided'])}}}"
        )
        macros.append(
            "\\newcommand{\\fiducialMinPte}"
            f"{{{_format_value(min_pte)}}}"
        )
        macros.append(
            "\\newcommand{\\fiducialMinPteStat}"
            f"{{{stat_latex.get(min_stat, min_stat)}}}"
        )
        full_calibration = calibration["full_range"]
        full_min_stat, full_min_pte = min(
            full_calibration["observed_ptes"].items(), key=lambda item: item[1]
        )
        macros.append(
            "\\newcommand{\\mockPGlobalFull}"
            f"{{{100 * full_calibration['p_global_one_sided']:.0f}\\%}}"
        )
        macros.append(
            "\\newcommand{\\mockMinPteFloorFull}"
            f"{{{_format_value(full_calibration['threshold_one_sided'])}}}"
        )
        macros.append(
            "\\newcommand{\\fullMinPte}"
            f"{{{_format_value(full_min_pte)}}}"
        )
        macros.append("")

    # Minimum over the six statistics of the ν−2 PTE (both fiducial scale-cut
    # boundaries treated as fitted), fiducial catalogue at the fiducial cuts:
    # the same computation as the nu_penalty_verdicts table, on the same two
    # PTE payloads.
    if reporting is not None and config_pte_path.exists() and harmonic_pte_path.exists():
        from emit_nu_penalty_verdicts import penalized_rows
        from scale_cuts import resolve_fiducial_bin_window

        first_bin, last_bin = resolve_fiducial_bin_window(reporting, scale_cut_convention)
        with open(config_pte_path) as f:
            config_space_versions = json.load(f)["evidence"]["versions"]
        with open(harmonic_pte_path) as f:
            harmonic_versions = json.load(f)["evidence"]["versions"]
        rows = [
            row
            for row in penalized_rows(
                config_space_versions, harmonic_versions, last_bin + 1 - first_bin
            )
            if row["version_full"] == fiducial_version and row["cut"] == "fiducial"
        ]
        macros.append("% minimum ν−2 PTE at the fiducial cuts (fiducial catalogue)")
        macros.append(
            "\\newcommand{\\fiducialMinPteNuPenalty}"
            f"{{{_format_value(min(float(row['pte_penalized']) for row in rows))}}}"
        )
        macros.append("")

    # Object-wise PSF-leakage correction: the largest PTE shift it induces,
    # over catalogue versions, statistics and both windows.
    if config_pte_path.exists() and harmonic_pte_path.exists():
        with open(config_pte_path) as f:
            config_space_versions = json.load(f)["evidence"]["versions"]
        with open(harmonic_pte_path) as f:
            harmonic_versions = json.load(f)["evidence"]["versions"]
        pte_keys = ("pte_at_fiducial", "pte_at_full_range")
        shifts = []
        for versions, stat_dicts in [
            (config_space_versions, lambda v: [v.get(s, {}) for s in _CONFIG_STATS]),
            (harmonic_versions, lambda v: [v]),
        ]:
            for ver, corr in versions.items():
                if not ver.endswith("_leak_corr"):
                    continue
                raw = versions.get(ver.removesuffix("_leak_corr"))
                if raw is None:
                    continue
                for stat_corr, stat_raw in zip(stat_dicts(corr), stat_dicts(raw)):
                    shifts.extend(
                        abs(stat_corr[k] - stat_raw[k])
                        for k in pte_keys
                        if k in stat_corr and k in stat_raw
                    )
        if shifts:
            macros.append(
                "% object-wise PSF-leakage correction: max |PTE(leak_corr) - PTE(raw)|"
                " over versions, statistics and both windows"
            )
            macros.append(
                f"\\newcommand{{\\leakCorrMaxPteShift}}{{{_format_value(max(shifts))}}}"
            )
            macros.append("")

    # GLASS mock covariance validation: empirical/analytic sigma ratios and
    # the chi^2 sampling-distribution check (Sect. 3.5 / 3.7 prose).
    if mock_campaign_evidence_path is not None and mock_campaign_evidence_path.exists():
        with open(mock_campaign_evidence_path) as f:
            campaign = json.load(f)
        ratios = campaign["sigma_ratios"]
        pure_medians = [
            ratios["xi_plus_B_7_cut_bins"]["summary"]["median"],
            ratios["xi_minus_B_7_cut_bins"]["summary"]["median"],
        ]
        cosebi_median = ratios["COSEBI_B_modes_1_to_20"]["summary"]["median"]
        cl_median = ratios["C_ell_BB_17_cut_bands"]["summary"]["median"]
        chi2 = campaign["chi2_calibration"]
        config_chi2_nu = [
            chi2[k]["chi2_mean"] / chi2[k]["dof"]
            for k in ("B_n<=6", "B_n<=20", "xi+^B", "xi-^B", "xi_tot^B")
        ]
        # The evidence stores empirical/analytic; the paper and Fig. 6 quote
        # analytic/empirical, so that below one reads "the analytic covariance
        # is tighter than the mock scatter".
        macros.append("% GLASS mock covariance validation (in-cut medians, analytic / empirical)")
        macros.append(f"\\newcommand{{\\mockSigmaRatioPureMin}}{{\\num{{{1 / max(pure_medians):.2f}}}}}")
        macros.append(f"\\newcommand{{\\mockSigmaRatioPureMax}}{{\\num{{{1 / min(pure_medians):.2f}}}}}")
        macros.append(f"\\newcommand{{\\mockSigmaRatioCosebis}}{{\\num{{{1 / cosebi_median:.2f}}}}}")
        macros.append(f"\\newcommand{{\\mockSigmaRatioCl}}{{\\num{{{1 / cl_median:.2f}}}}}")
        macros.append(f"\\newcommand{{\\mockChiTwoNuConfigMin}}{{\\num{{{min(config_chi2_nu):.2f}}}}}")
        macros.append(f"\\newcommand{{\\mockChiTwoNuConfigMax}}{{\\num{{{max(config_chi2_nu):.2f}}}}}")
        macros.append("")

    # Clean-sample failure rate at the adopted threshold, fiducial window,
    # from the scale-cut scan (the letter's "a clean sample fails it X% of the time").
    if (
        mock_scale_cut_scan_path is not None
        and mock_scale_cut_scan_path.exists()
        and pte_threshold is not None
    ):
        with open(mock_scale_cut_scan_path) as f:
            scan = json.load(f)
        fid = list(scan["fiducial_window_edges"])
        key = f"alpha_{pte_threshold:g}".replace(".", "p")
        window = next(
            w for w in scan["windows"]
            if [w["edge_index_min"], w["edge_index_max"]] == fid
        )
        if key in window:
            macros.append("% clean-sample failure rate at the adopted threshold (fiducial window)")
            macros.append(f"\\newcommand{{\\mockAlphaFiducial}}{{{100 * window[key]:.0f}\\%}}")
            macros.append("")

    if survey_properties_path is not None and survey_properties_path.exists():
        with open(survey_properties_path) as f:
            survey = json.load(f)
        macros.append("% survey properties (fiducial catalogue, Table 1 row)")
        macros.append(f"\\newcommand{{\\surveyArea}}{{\\num{{{survey['area']:.0f}}}}}")
        macros.append(f"\\newcommand{{\\surveyNeff}}{{\\num{{{survey['n_eff']:.2f}}}}}")
        # sigma_e_combined is the two-component dispersion; the paper quotes
        # the per-component value.
        macros.append(
            f"\\newcommand{{\\surveySigmaE}}{{\\num{{{survey['sigma_e_combined'] / math.sqrt(2):.2f}}}}}"
        )
        macros.append("")

    first_mode = None
    if cosebis_modes_path is not None and cosebis_modes_path.exists():
        import numpy as np

        cosebis_modes = np.load(cosebis_modes_path)
        first_mode = {
            "full_range_significance": float(
                cosebis_modes["full_Bn"][0] / cosebis_modes["full_sigma_B"][0]
            ),
            "fiducial_cut_significance": float(
                cosebis_modes["fiducial_Bn"][0] / cosebis_modes["fiducial_sigma_B"][0]
            ),
        }
        macros.append(
            "% COSEBI first-mode significance B_1/sigma_1 (fiducial catalogue, analytic sigma)"
        )
        macros.append(
            "\\newcommand{\\cosebisFirstModeSignificanceFull}"
            f"{{\\num{{{first_mode['full_range_significance']:.1f}}}}}"
        )
        macros.append(
            "\\newcommand{\\cosebisFirstModeSignificanceFid}"
            f"{{\\num{{{first_mode['fiducial_cut_significance']:.2f}}}}}"
        )
        macros.append("")

    # Analytic sigma over the empirical scatter of the GLASS realizations,
    # full angular range; "tighter by X%" is 1 - analytic/empirical.
    if mock_per_mock_statistics_path is not None and mock_per_mock_statistics_path.exists():
        import numpy as np

        per_mock = np.load(mock_per_mock_statistics_path)
        r1 = per_mock["sigma_cosebis_full"][0] / np.std(
            per_mock["Bn_full"][:, 0], ddof=1
        )
        large_theta = per_mock["theta"] > 100
        pure_ratios = np.concatenate([
            per_mock[f"sigma_{xi}_full"][large_theta]
            / np.std(per_mock[f"{xi}_B_full"][:, large_theta], axis=0, ddof=1)
            for xi in ("xip", "xim")
        ])
        macros.append("% GLASS mock scatter vs analytic sigma, full range (analytic / empirical)")
        macros.append(
            f"\\newcommand{{\\mockCosebisFirstModeTighter}}{{{100 * (1 - r1):.0f}\\%}}"
        )
        if first_mode is not None:
            macros.append(
                "\\newcommand{\\mockCosebisFirstModeSignificance}"
                f"{{\\num{{{first_mode['full_range_significance'] * r1:.1f}}}}}"
            )
        macros.append(
            "\\newcommand{\\mockPureLargeThetaTighter}"
            f"{{{100 * (1 - np.median(pure_ratios)):.0f}\\%}}"
        )
        macros.append("")

    if mock_mean_vector_stats_path is not None and mock_mean_vector_stats_path.exists():
        with open(mock_mean_vector_stats_path) as f:
            mean_stats = json.load(f)
        bias = mean_stats["statistics"]["B_n"]["scale_averaged"]["max_abs_mean_normalized"]
        macros.append(
            "% GLASS mock ensemble mean B-mode bias (COSEBIs, max |mean|/sigma over modes)"
        )
        macros.append(f"\\newcommand{{\\mockMeanBiasCosebis}}{{\\num{{{bias:.2f}}}}}")
        macros.append("")

    if mock_noise_table_path is not None and mock_noise_table_path.exists():
        with open(mock_noise_table_path, newline="") as f:
            rows = list(csv.DictReader(f))
        n_eff_mock = next(
            float(r["n_eff_arcmin2"]) for r in rows if "GLASS" in r["catalogue"]
        )
        n_eff_data = next(
            float(r["n_eff_arcmin2"]) for r in rows if "GLASS" not in r["catalogue"]
        )
        macros.append("% GLASS mock galaxy density relative to the data")
        macros.append(
            "\\newcommand{\\mockDensityExcess}"
            f"{{{100 * (n_eff_mock / n_eff_data - 1):.0f}\\%}}"
        )
        macros.append("")

    # Diagonal xi_pm covariance: 20 xi_+ bins then 20 xi_- bins.
    if (
        cov_reporting_g_path is not None
        and cov_reporting_ng_path is not None
        and cov_reporting_g_path.exists()
        and cov_reporting_ng_path.exists()
        and reporting is not None
    ):
        import numpy as np
        from scale_cuts import resolve_fiducial_bin_window

        first_bin, last_bin = resolve_fiducial_bin_window(reporting, scale_cut_convention)
        frac = 1 - np.diag(np.loadtxt(cov_reporting_g_path)) / np.diag(
            np.loadtxt(cov_reporting_ng_path)
        )
        n_theta = len(frac) // 2
        fid = np.r_[first_bin:last_bin + 1, n_theta + first_bin:n_theta + last_bin + 1]
        macros.append("% non-Gaussian share of the diagonal xi_pm variance, 1 - G/(G+NG)")
        macros.append(
            f"\\newcommand{{\\ngFractionDiagonalAll}}{{{100 * frac.mean():.0f}\\%}}"
        )
        macros.append(
            f"\\newcommand{{\\ngFractionDiagonalFiducial}}{{{100 * frac[fid].mean():.0f}\\%}}"
        )
        macros.append("")

    # Harmonic-config COSEBIS comparison - B-mode PTEs (modes 1-N) per angular range
    # These are sibling-analysis outputs in the lc layout, not claims-dir files.
    harmonic_config_paths = {
        "fiducial": harmonic_config_fiducial_path,
        "full": harmonic_config_full_path,
    }
    for angular_range in ["full", "fiducial"]:
        direct_path = harmonic_config_paths[angular_range]
        if direct_path is not None and direct_path.exists():
            with open(direct_path) as f:
                data = json.load(f)
            ev = data.get("evidence", data)
            range_suffix = "Full" if angular_range == "full" else "Fid"
            for method, method_prefix in [("harmonic_b_mode_ptes", "harmCosebis"), ("config_b_mode_ptes", "cfgCosebis")]:
                pte_data = ev.get(method, {}).get(fiducial_version, {})
                if pte_data.get("pte") is not None:
                    macros.append(f"\\newcommand{{\\{method_prefix}PteSixThree{range_suffix}}}{{{_format_value(pte_data['pte'])}}}")
            continue
        harm_cosebis_path = (
            claims_dir
            / f"harmonic_config_cosebis_comparison_{angular_range}"
            / "evidence.json"
        )
        if not harm_cosebis_path.exists():
            continue
        with open(harm_cosebis_path) as f:
            data = json.load(f)
        ev = data.get("evidence", {})
        range_suffix = "Full" if angular_range == "full" else "Fid"

        macros.append(
            f"% harmonic_config_cosebis_comparison_{angular_range} (B-mode COSEBIS PTEs)"
        )
        macros.append("")

        for method, method_prefix in [
            ("harmonic_b_mode_ptes", "harmCosebis"),
            ("config_b_mode_ptes", "cfgCosebis"),
        ]:
            ptes = ev.get(method, {})
            for ver, pte_data in ptes.items():
                short_ver = _parse_version_short(ver)
                word = VERSION_WORDS.get(short_ver, short_ver)
                pte = pte_data.get("pte")
                chi2 = pte_data.get("chi2")
                if pte is not None:
                    macros.append(
                        f"\\newcommand{{\\{method_prefix}Pte{word}{range_suffix}}}{{{_format_value(pte)}}}"
                    )
                if chi2 is not None:
                    macros.append(
                        f"\\newcommand{{\\{method_prefix}Chisq{word}{range_suffix}}}{{{_format_value(chi2)}}}"
                    )

        macros.append("")

    content = "\n".join(macros)
    for output_path in output_paths:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(content)
        print(f"  → {output_path}")


_CONFIG_STATS = [
    "cosebis_stats",
    "cosebis_20_stats",
    "xip_stats",
    "xim_stats",
    "combined_stats",
]

# Version slug for CSV output, keyed by full leak-corrected version string.
# Row-label values for the rendered MySTRA appendix table. Capitalized for
# display; they stay space-free (underscores, not spaces) because MySTRA's
# {astra:value where=} parser splits on spaces and cannot match a value that
# contains one. `{astra:value}` where-value matching is case-insensitive, so
# queries may still be written with lowercase slugs.
_VERSION_SLUGS = {
    "SP_v1.4.5_leak_corr": "Initial",
    "SP_v1.4.6.3_leak_corr": "Size_cuts",
    "SP_v1.4.8_leak_corr": "Masked",
    "SP_v1.4.11.3_leak_corr": "Relaxed_flags",
}

_VERSION_SLUGS.update({k.removesuffix("_leak_corr"): v for k, v in list(_VERSION_SLUGS.items())})

# Statistic column names, in CSV column order. They are `{astra:value col=}`
# query targets, so they stay space-free ASCII slugs matching the spec.
_STAT_HEADERS = ["cosebis_n6", "cosebis_n20", "xip_B", "xim_B", "xitot_B", "cl_BB"]


def _pte_row_values(pte_key, cfg, harm):
    """Build the 6 raw PTE values (floats) for one row, CSV column order."""
    values = [cfg.get(stat, {}).get(pte_key, float("nan")) for stat in _CONFIG_STATS]
    values.append(harm.get(pte_key, float("nan")))
    return values


def generate_pte_table_csv(
    out_file: Path,
    fiducial_version: str,
    versions: list,
    version_labels: dict,
    config_pte_path: Path,
    harmonic_pte_path: Path,
):
    """Write the N x 6 PTE CSV (all versions, fiducial + full-range rows)."""
    config_data = {}
    if config_pte_path.exists():
        with open(config_pte_path) as f:
            config_data = json.load(f).get("evidence", {}).get("versions", {})

    harmonic_data = {}
    if harmonic_pte_path.exists():
        with open(harmonic_pte_path) as f:
            harmonic_data = json.load(f).get("evidence", {}).get("versions", {})

    # Filter to only leak_corr versions (those with labels in version_labels)
    table_versions = [v for v in versions if v in version_labels]

    rows = []
    for ver in table_versions:
        cfg = config_data.get(ver, {})
        harm = harmonic_data.get(ver, {})
        for pte_key, cut_slug in [
            ("pte_at_fiducial", "Fiducial"),
            ("pte_at_full_range", "Full_range"),
        ]:
            rows.append(
                [
                    _VERSION_SLUGS.get(ver, ver),
                    ver,
                    cut_slug,
                    *(_sig3(v) for v in _pte_row_values(pte_key, cfg, harm)),
                ]
            )

    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["version", "version_full", "cut", *_STAT_HEADERS])
        writer.writerows(rows)
    print(f"  \u2192 {out_file}")


def aggregate_pte_evidence(
    out_file: Path,
    fiducial_version: str,
    versions: list,
    version_labels: dict,
    config_pte_path: Path,
    harmonic_pte_path: Path,
):
    """Write the aggregated PTE JSON evidence payload.

    Holds the six paper PTE statistics at the fiducial and full-range cuts for
    every catalog version, gathered from the config-space and harmonic-space
    PTE evidence files.
    """
    config_data = {}
    if config_pte_path.exists():
        with open(config_pte_path) as f:
            config_data = json.load(f).get("evidence", {}).get("versions", {})

    harmonic_data = {}
    if harmonic_pte_path.exists():
        with open(harmonic_pte_path) as f:
            harmonic_data = json.load(f).get("evidence", {}).get("versions", {})

    stat_keys = list(_STAT_HEADERS)
    table_versions = [v for v in versions if v in version_labels]

    payload = {}
    for ver in table_versions:
        cfg = config_data.get(ver, {})
        harm = harmonic_data.get(ver, {})
        cuts = {}
        for pte_key, cut_slug in [
            ("pte_at_fiducial", "fiducial"),
            ("pte_at_full_range", "full_range"),
        ]:
            values = _pte_row_values(pte_key, cfg, harm)
            cuts[cut_slug] = {
                k: (None if isinstance(v, float) and math.isnan(v) else v)
                for k, v in zip(stat_keys, values)
            }
        payload[ver] = {
            "label": _VERSION_SLUGS.get(ver, version_labels.get(ver, ver)),
            "cuts": cuts,
        }

    evidence = {
        "generated": datetime.now().isoformat(),
        "fiducial_version": fiducial_version,
        "statistics": stat_keys,
        "versions": payload,
    }

    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w") as f:
        json.dump(evidence, f, indent=2)
    print(f"  \u2192 {out_file}")


def generate_evidence(
    spec_id: str,
    spec_path: str,
    depends_on: list[str],
    claims_dir: Path,
    output_path: Path,
):
    """Generate evidence.json for dashboard dependency tracking."""
    # Collect summary from dependent claims
    summary = {}
    for dep in depends_on:
        dep_evidence = claims_dir / dep / "evidence.json"
        if dep_evidence.exists():
            with open(dep_evidence) as f:
                data = json.load(f)
            summary[dep] = {
                "has_evidence": True,
                "generated": data.get("generated"),
            }
        else:
            summary[dep] = {"has_evidence": False}

    evidence = {
        "spec_id": spec_id,
        "spec_path": spec_path,
        "depends_on": depends_on,
        "generated": datetime.now().isoformat(),
        "evidence": {
            "type": "paper_integration",
            "description": "Aggregates quantitative claims for paper reporting",
            "dependencies_summary": summary,
        },
        "output": {"macros": "claims_macros.tex"},
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(evidence, f, indent=2)
    print(f"  → {output_path}")


